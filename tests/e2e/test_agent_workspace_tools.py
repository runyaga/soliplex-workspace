"""E2E: agent tool calling via pydantic-ai FunctionModel.

An actual pydantic-ai Agent with workspace tools bound via
``make_workspace_tools()`` executes deterministic tool calls through
FunctionModel — no LLM API key required.

Note: pydantic-ai propagates tool exceptions directly (only
``ModelRetry`` is caught for retry).  Workspace errors like
``WorkspaceFileNotFoundError`` surface as unhandled exceptions.
Production integration should wrap tools to convert workspace
errors into ``ModelRetry`` for graceful LLM-driven recovery.
"""

from __future__ import annotations

import inspect
import uuid

import pytest
from pydantic_ai import Agent
from pydantic_ai import ModelMessage
from pydantic_ai import ModelResponse
from pydantic_ai import TextPart
from pydantic_ai import ToolCallPart
from pydantic_ai.models.function import AgentInfo
from pydantic_ai.models.function import FunctionModel

from soliplex_workspace.exceptions import WorkspaceAlreadyExistsError
from soliplex_workspace.exceptions import WorkspaceFileNotFoundError
from soliplex_workspace.providers.mock import MockWorkspaceProvider
from soliplex_workspace.tools.bridge import make_workspace_tools

pytestmark = pytest.mark.e2e


def _room_id() -> str:
    return f"agent-{uuid.uuid4().hex[:8]}"


# -- Deterministic model functions ---------------------------------


def _workspace_agent_model(
    messages: list[ModelMessage],
    info: AgentInfo,  # noqa: ARG001
) -> ModelResponse:
    """Calls list -> read -> write, then returns text."""
    tool_returns = [
        p for m in messages for p in m.parts if p.part_kind == "tool-return"
    ]
    step = len(tool_returns)

    if step == 0:
        return ModelResponse(
            parts=[
                ToolCallPart(
                    "workspace_list",
                    {"path": "/", "recursive": True},
                )
            ]
        )
    if step == 1:
        return ModelResponse(
            parts=[
                ToolCallPart(
                    "workspace_read",
                    {"path": "/notes/readme.md"},
                )
            ]
        )
    if step == 2:
        return ModelResponse(
            parts=[
                ToolCallPart(
                    "workspace_write",
                    {
                        "path": "/summary.md",
                        "content": "# Summary\nGenerated by agent.",
                    },
                )
            ]
        )
    return ModelResponse(
        parts=[TextPart("I read the workspace and wrote a summary.")]
    )


def _read_nonexistent_model(
    messages: list[ModelMessage],
    info: AgentInfo,  # noqa: ARG001
) -> ModelResponse:
    """Tries to read a file that doesn't exist."""
    return ModelResponse(
        parts=[
            ToolCallPart(
                "workspace_read",
                {"path": "/nonexistent.txt"},
            )
        ]
    )


def _overwrite_direct_model(
    messages: list[ModelMessage],
    info: AgentInfo,  # noqa: ARG001
) -> ModelResponse:
    """Writes with overwrite=True directly."""
    tool_returns = [
        p for m in messages for p in m.parts if p.part_kind == "tool-return"
    ]
    if len(tool_returns) == 0:
        return ModelResponse(
            parts=[
                ToolCallPart(
                    "workspace_write",
                    {
                        "path": "/existing.txt",
                        "content": "new content",
                        "overwrite": True,
                    },
                )
            ]
        )
    return ModelResponse(parts=[TextPart("File overwritten successfully.")])


def _overwrite_blocked_model(
    messages: list[ModelMessage],
    info: AgentInfo,  # noqa: ARG001
) -> ModelResponse:
    """Tries to write without overwrite (should fail)."""
    return ModelResponse(
        parts=[
            ToolCallPart(
                "workspace_write",
                {
                    "path": "/existing.txt",
                    "content": "new content",
                },
            )
        ]
    )


def _empty_write_model(
    messages: list[ModelMessage],
    info: AgentInfo,  # noqa: ARG001
) -> ModelResponse:
    """Writes an empty file, then reads it back."""
    tool_returns = [
        p for m in messages for p in m.parts if p.part_kind == "tool-return"
    ]
    step = len(tool_returns)

    if step == 0:
        return ModelResponse(
            parts=[
                ToolCallPart(
                    "workspace_write",
                    {"path": "/empty.txt", "content": ""},
                )
            ]
        )
    if step == 1:
        return ModelResponse(
            parts=[
                ToolCallPart(
                    "workspace_read",
                    {"path": "/empty.txt"},
                )
            ]
        )
    return ModelResponse(parts=[TextPart("Empty file created and verified.")])


