def _lazy_write_model(
    messages: list[ModelMessage],
    info: AgentInfo,  # noqa: ARG001
) -> ModelResponse:
    """Writes a file — workspace should be auto-created."""
    tool_returns = [
        p for m in messages for p in m.parts if p.part_kind == "tool-return"
    ]
    if len(tool_returns) == 0:
        return ModelResponse(
            parts=[
                ToolCallPart(
                    "workspace_write",
                    {"path": "/auto.txt", "content": "auto-created"},
                )
            ]
        )
    return ModelResponse(parts=[TextPart("Workspace was lazily created.")])


class TestAgentLazyWorkspaceCreation:
    """Agent workspace tools auto-create workspace on first call."""

    async def test_agent_lazy_workspace_creation(self):
        provider = MockWorkspaceProvider()
        room_id = _room_id()
        # No workspace pre-created
        tools = make_workspace_tools(provider, room_id)

        agent: Agent[None, str] = Agent(
            FunctionModel(_lazy_write_model),
            tools=tools,
        )
        result = await agent.run("Write to a new workspace")
        assert "lazily" in result.output.lower()

        # Workspace was auto-created
        ws = await provider.get_workspace(room_id)
        assert ws is not None

        # File was written
        data = await provider.download_file(room_id, "/auto.txt")
        assert data == b"auto-created"
